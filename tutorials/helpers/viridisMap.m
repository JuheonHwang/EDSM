function cmap = viridisMap(n)
%VIRIDISMAP  n x 3 viridis colormap (interpolated from 11 anchor colors).
if nargin < 1, n = 256; end
a = [0.267004 0.004874 0.329415; 0.282327 0.140926 0.457517; 0.253935 0.265254 0.529983
     0.206756 0.371758 0.553117; 0.163625 0.471133 0.558148; 0.127568 0.566949 0.550556
     0.134692 0.658636 0.517649; 0.266941 0.748751 0.440573; 0.477504 0.821444 0.318195
     0.741388 0.873449 0.149561; 0.993248 0.906157 0.143936];
x = linspace(0, 1, size(a, 1));
cmap = interp1(x, a, linspace(0, 1, n));
end
