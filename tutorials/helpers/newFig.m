function fig = newFig(ctx, widthIn, heightIn)
%NEWFIG  New figure with the shared style (white background, readable fonts).
%
%   fig = newFig(ctx, 8, 4.5)   % size in inches; saved at 150 dpi -> 1200 x 675 px
%
%   Invisible when MATLAB has no desktop (batch), visible otherwise.
if nargin < 2, widthIn = 8; end
if nargin < 3, heightIn = 4.5; end
vis = 'off'; if ctx.interactive, vis = 'on'; end
fig = figure('Visible', vis, 'Color', 'w', 'Units', 'inches', 'Position', [1 1 widthIn heightIn], ...
    'InvertHardcopy', 'off');
try, theme(fig, 'light'); catch, end %#ok<NOCOM>
set(fig, 'Color', 'w', ...
    'DefaultAxesFontSize', 11, 'DefaultAxesBox', 'on', 'DefaultAxesLineWidth', 0.8, ...
    'DefaultAxesXGrid', 'on', 'DefaultAxesYGrid', 'on', 'DefaultAxesGridAlpha', 0.18, 'DefaultAxesXMinorGrid', 'off', 'DefaultAxesYMinorGrid', 'off', ...
    'DefaultAxesColor', 'w', 'DefaultAxesXColor', [0.15 0.15 0.15], 'DefaultAxesYColor', [0.15 0.15 0.15], ...
    'DefaultAxesTitleFontWeight', 'normal', 'DefaultAxesTitleFontSizeMultiplier', 1.05, ...
    'DefaultLineLineWidth', 1.8, 'DefaultLineMarkerSize', 6, ...
    'DefaultTextColor', [0.15 0.15 0.15], 'DefaultLegendFontSize', 10);
end
